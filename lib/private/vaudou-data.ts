export interface VaudouBaseEntry {
  id: string;
  categorie: string;
  sousCategorie: string;
  nomCreole: string;
  nomFrancais: string;
  sacreSymbolique: string;
  dimensionCulturelle: string;
  tags: string[];
}

export interface LoaEntry extends VaudouBaseEntry {
  type: 'loa';
  famille: string;
  correspondanceAfricaine?: string;
  couleurs: string[];
  niveauSacralite: 'SACRÉ' | 'Emblématique' | 'Culturel' | 'Ambivalent' | 'Symbolique';
}

export interface AnimalEntry extends VaudouBaseEntry {
  type: 'animal';
  famille: string;
  nomScientifique?: string;
  niveauSacralite: 'SACRÉ' | 'Emblématique' | 'Culturel' | 'Ambivalent' | 'Symbolique';
}

export interface PlanteEntry extends VaudouBaseEntry {
  type: 'plante';
  famille: string;
  nomScientifique?: string;
  niveauSacralite: 'SACRÉ' | 'Emblématique' | 'Culturel' | 'Symbolique';
}

export interface ObjetEntry extends VaudouBaseEntry {
  type: 'objet';
  famille: string;
  description: string;
  niveauSacralite: 'SACRÉ' | 'Emblématique' | 'Culturel' | 'Symbolique';
}

export interface LieuEntry extends VaudouBaseEntry {
  type: 'lieu';
  famille: string;
  localisation?: string;
  niveauSacralite: 'SACRÉ' | 'Emblématique' | 'Culturel' | 'Symbolique';
}

export interface RituelEntry extends VaudouBaseEntry {
  type: 'rituel';
  famille: string;
  description: string;
  niveauSacralite: 'SACRÉ' | 'Emblématique' | 'Culturel' | 'Symbolique';
}

export interface ChantEntry extends VaudouBaseEntry {
  type: 'chant';
  famille: string;
  description: string;
  rythme?: string;
  niveauSacralite: 'SACRÉ' | 'Emblématique' | 'Culturel' | 'Symbolique';
}

export interface DateRituelleEntry extends VaudouBaseEntry {
  type: 'date';
  famille: string;
  datePeriod: string;
  niveauSacralite: 'SACRÉ' | 'Emblématique' | 'Culturel' | 'Symbolique';
}

// Union type pour toutes les entrées
export type VaudouEntry = 
  | LoaEntry 
  | AnimalEntry 
  | PlanteEntry 
  | ObjetEntry 
  | LieuEntry 
  | RituelEntry 
  | ChantEntry 
  | DateRituelleEntry;

// Type guard helpers
export function isLoaEntry(entry: VaudouEntry): entry is LoaEntry {
  return entry.type === 'loa';
}
export function isAnimalEntry(entry: VaudouEntry): entry is AnimalEntry {
  return entry.type === 'animal';
}
export function isPlanteEntry(entry: VaudouEntry): entry is PlanteEntry {
  return entry.type === 'plante';
}
export function isObjetEntry(entry: VaudouEntry): entry is ObjetEntry {
  return entry.type === 'objet';
}
export function isLieuEntry(entry: VaudouEntry): entry is LieuEntry {
  return entry.type === 'lieu';
}
export function isRituelEntry(entry: VaudouEntry): entry is RituelEntry {
  return entry.type === 'rituel';
}
export function isChantEntry(entry: VaudouEntry): entry is ChantEntry {
  return entry.type === 'chant';
}
export function isDateRituelleEntry(entry: VaudouEntry): entry is DateRituelleEntry {
  return entry.type === 'date';
}


