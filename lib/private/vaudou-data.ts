// FONCTION UTILITAIRE DE NORMALISATION
// ============================================
export function normalizeForComparison(name: string): string {
  return name
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/s+/g, '');
}

